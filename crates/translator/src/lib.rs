//! Translates N64 (MIPS VR4300, big-endian) machine code into Rust source.
//!
//! The generated Rust links against `n64rusty-runtime`. Each guest function
//! becomes one Rust function that takes `&mut Ctx`; calls between guest
//! functions go through `Ctx::call`, so any of them can be overridden by
//! address. See [`emit`] for how blocks and branch delay slots are handled.
//!
//! Supported so far: the whole integer instruction set except traps, LL/SC
//! and coprocessor instructions, which emit a call that panics with the
//! address. Overflow exceptions (ADD, ADDI, SUB, DADD, DADDI, DSUB) are not
//! raised.

use std::fmt;

pub mod decode;
pub mod discover;
pub mod emit;

pub use decode::{Flow, Inst, Op};

/// Crate version, for reports written next to generated output.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// A guest function: its address and its instruction words.
#[derive(Clone, Debug)]
pub struct Function {
    /// Guest virtual address of the first instruction.
    pub addr: u32,
    /// Instruction words from `addr` up to the function end.
    pub words: Vec<u32>,
    /// Extra block starts found by analysis, such as jump table targets.
    pub jump_targets: Vec<u32>,
    /// Optional name, written as a doc comment.
    pub name: Option<String>,
}

impl Function {
    /// A function with no extra block starts and no name.
    pub fn new(addr: u32, words: Vec<u32>) -> Self {
        Self {
            addr,
            words,
            jump_targets: Vec::new(),
            name: None,
        }
    }
}

/// A translation failure at a guest address.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TranslateError {
    /// Guest address of the problem.
    pub addr: u32,
    /// What went wrong.
    pub msg: String,
}

impl TranslateError {
    fn new(addr: u32, msg: impl Into<String>) -> Self {
        Self {
            addr,
            msg: msg.into(),
        }
    }
}

impl fmt::Display for TranslateError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{:#010x}: {}", self.addr, self.msg)
    }
}

impl std::error::Error for TranslateError {}

/// Rust source for one guest function.
pub fn translate_function(f: &Function) -> Result<String, TranslateError> {
    emit::function(f)
}

/// Rust source for a set of functions plus a `register` function that adds
/// them all to a `Ctx`.
pub fn translate_module(funcs: &[Function]) -> Result<String, TranslateError> {
    let mut out =
        format!("// Generated by n64rusty-translator {VERSION}. Do not edit; do not commit.\n\n");
    for f in funcs {
        out.push_str(&translate_function(f)?);
        out.push('\n');
    }
    out.push_str("/// Registers every function in this module.\n");
    out.push_str("pub fn register(ctx: &mut ::n64rusty_runtime::Ctx) {\n");
    for f in funcs {
        out.push_str(&format!(
            "    ctx.register({:#010x}, {});\n",
            f.addr,
            emit::fn_name(f.addr)
        ));
    }
    out.push_str("}\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_branch_in_delay_slot() {
        // beq $0, $0, +1 ; beq $0, $0, +1
        let f = Function::new(0x8000_1000, vec![0x1000_0001, 0x1000_0001, 0, 0]);
        let e = translate_function(&f).unwrap_err();
        assert_eq!(e.addr, 0x8000_1004);
    }

    #[test]
    fn emits_register_function() {
        // jr $ra ; nop
        let f = Function::new(0x8000_1000, vec![0x03E0_0008, 0]);
        let src = translate_module(&[f]).unwrap();
        assert!(src.contains("pub fn f_80001000("));
        assert!(src.contains("ctx.register(0x80001000, f_80001000);"));
    }
}
